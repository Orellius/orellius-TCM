/**
 * Get a translated string by key and language.
 * Falls back to English, then to the raw key.
 */
export function t(key: string, lang: Lang = "he"): string {
  const entry = translations[key];
  if (!entry) return key;
  return entry[lang] ?? entry["en"] ?? key;
}

