export const REGION_KEYS = Object.keys(regionNames);

/**
 * Translate a snake_case region key to a display name.
 * Falls back to Title Case conversion if the region isn't in the map.
 */
export function translateRegion(region: string, lang: Lang = "he"): string {
  const entry = regionNames[region];
  if (entry) return entry[lang] ?? entry["en"];
  // Fallback: convert snake_case to Title Case
  return region
    .split("_")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}

